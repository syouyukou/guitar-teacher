export function getLessonHomeworkVideos(lesson: Lesson): {
  homework: string[];
  videoResources: LessonVideoResource[];
} {
  const homework = HOMEWORK[lesson.id];
  if (!homework) {
    return {
      homework: [
        "複習本課「學習內容」主題，自行寫 3 句心得。",
        "節選本課推薦曲 20～30 秒慢練，錄一段自查。",
        "整理一句下次問老師或問答輔助用的問題。",
      ],
      videoResources: buildDefaultVideos(lesson),
    };
  }

  return {
    homework,
    videoResources: buildDefaultVideos(lesson),
  };
}

function buildDefaultVideos(lesson: Lesson): LessonVideoResource[] {
  const zhYt = `${lesson.youtubeSearch} 電吉他 教學 中文`;
  const bilibiliKw = `${lesson.youtubeSearch} 电吉他教学`;
  return [
    {
      title: "YouTube：用本課關鍵字搜尋（建議加「教學」「中文」）",
      href: ytZh(zhYt),
      note: "依帳號地區與演算法顯示不同結果，請挑示範清楚、節奏可跟的影片。",
    },
    {
      title: "Bilibili：中文內容搜尋",
      href: bilibiliSearch(bilibiliKw),
      note: "介面多為簡體屬正常；若無法使用本站其餘資源仍可透過 YouTube。",
    },
  ];
}
